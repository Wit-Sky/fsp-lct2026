@template("bas.nav.distance_time", SPEC, TOPIC, -1.4, "number",
          "Путь = скорость × время с переводом единиц — базовый уровень.")
def _dist(rng):
    v, t = rng.randint(3, 30), rng.randint(1, 20)
    return {"text": f"Квадрокоптер летит по прямой с постоянной путевой скоростью {v} м/с. Какое расстояние в метрах он пролетит за {t} мин?",
            "answer": v * t * 60}


@template("bas.nav.lat_km", SPEC, TOPIC, -0.6, "number",
          "Один градус широты ≈ 111 км — оценка расстояния по координатам.")
def _lat(rng):
    d = rng.choice([0.01, 0.02, 0.05, 0.1, 0.2, 0.5])
    lat0 = round(rng.uniform(44, 68), 2)
    return {"text": f"Точка A: {lat0:.2f}° с. ш., точка B: {lat0 + d:.2f}° с. ш., долгота одинаковая. "
                    f"Примите 1° широты = 111 км. Каково расстояние между точками в метрах?",
            "answer": round(d * 111_000)}


@template("bas.nav.lon_cos", SPEC, TOPIC, 0.2, "number",
          "Длина градуса долготы зависит от широты (× cos φ) — частая ошибка в расчётах.")
def _lon(rng):
    k = rng.randint(1, 40)                                   # разница долгот k/100 градуса
    lat, c = rng.choice([(30, 866), (40, 766), (45, 707), (50, 643), (55, 574), (60, 500), (65, 423)])   # cos × 1000
    ds, cs = f"{k / 100:g}".replace(".", ","), f"{c / 1000:g}".replace(".", ",")
    return {"text": f"Две точки на широте {lat}° с. ш. различаются по долготе на {ds}°. Примите 1° по экватору = 111 км, "
                    f"cos {lat}° = {cs}. Каково расстояние между точками в метрах (округлите до целого)?",
            "answer": (111 * k * c * 2 + 100) // 200}           # 111 000 м × k/100 × c/1000, округление «половина вверх»


@template("bas.nav.gnss_facts", SPEC, TOPIC, 0.5, "single",
          "Базовые факты GNSS: решение 3D, DOP, системы.")
def _gnss(rng):
    text, ans, wrong = rng.choice([
        ("Какое минимальное число спутников нужно приёмнику для 3D-решения (широта, долгота, высота + поправка часов)?",
         "4", ["2", "3", "6"]),
        ("Как меняется точность позиционирования при росте HDOP с 0,8 до 3,5?", "ухудшается",
         ["улучшается", "не меняется", "растёт только точность по высоте"]),
        ("Какая из систем — российская глобальная навигационная спутниковая система?", "ГЛОНАСС",
         ["Galileo", "BeiDou", "GPS"]),
        ("Какой порядок горизонтальной точности даёт RTK с фиксированным решением (fix)?", "единицы сантиметров",
         ["единицы метров", "десятки метров", "сотни метров"]),
    ])
    return {"text": text, **choice(rng, ans, wrong)}


@template("bas.nav.wind_roundtrip", SPEC, TOPIC, 1.0, "number",
          "Ветер вдоль маршрута «туда-обратно»: время больше, чем без ветра — нужно считать оба плеча.")
def _wind(rng):
    while True:                      # d кратно НОК(v − w, v + w): время по каждому плечу — целое число секунд
        v, w = rng.randint(10, 30), rng.randint(2, 8)
        if v - w < 6:
            continue
        lcm = math.lcm(v - w, v + w)
        ks = [k for k in range(1, 400) if 600 <= k * lcm <= 6000]
        if ks:
            d = rng.choice(ks) * lcm
            break
    return {"text": f"Воздушная скорость БВС {v} м/с, встречный ветер на пути «туда» {w} м/с (на обратном — попутный). "
                    f"Длина маршрута в одну сторону {d} м. Сколько секунд займёт полёт туда и обратно?",
            "answer": d // (v - w) + d // (v + w)}


@template("bas.nav.kalman", SPEC, TOPIC, 1.6, "number",
          "Шаг фильтра Калмана в 1D: прогноз дисперсии P+Q, коэффициент K = P/(P+R), коррекция оценки.")
def _kalman(rng):
    while True:
        p, q, r = rng.choice([1, 2, 3, 4, 6]), rng.choice([0, 1, 2]), rng.choice([2, 4, 6, 8, 12])
        x, z = rng.randint(10, 50), 0
        z = x + rng.choice([-6, -4, -3, 3, 4, 6, 8])
        pp = p + q
        k = pp / (pp + r)
        new = x + k * (z - x)
        if abs(new * 100 - round(new * 100)) < 1e-9:
            break
    return {"text": (f"Одномерный фильтр Калмана высоты. Оценка x = {x} м, дисперсия P = {p}, шум процесса Q = {q} "
                     f"(модель — высота постоянна). Пришло измерение z = {z} м с дисперсией шума R = {r}. "
                     f"Какой будет новая оценка высоты после шагов прогноза и коррекции? (до сотых)"),
            "answer": round(new, 2)}
